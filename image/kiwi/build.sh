# image/kiwi/build.sh - the generic install image, PC / CI side, end to end. Runs as root INSIDE a privileged Fedora 44 aarch64
# container (loop devices, mounts, chroot): natively on an arm64 host (GitHub ubuntu-24.04-arm), or on x86 under
# qemu-user-static + binfmt (slow; see ci/README in the report). Never touches a tablet; publishes nothing.
#   build.sh INPUT_DIR OUT_DIR
# Steps (each prints one "build:" line; any FAIL stops the build):
#   1 local repo   tools/build-local-repo.sh: our rpms (kernel / firmware as published, libssc / iio-sensor-proxy / device rebuilt)
#   2 kiwi         kiwi-ng system build (desc/config.kiwi + config.sh + edit_boot_install.sh + root/)
#   3 golden       tools/kiwi2golden.py: B149 partition names, the ESP as FAT32 / 4096, golden format
#   4 small        mk-small.py: the minimum-size disk (grows at the first boot)
#   5 check        tools/image-check.sh: gen_check + layout + boot + initramfs + manifest vs B149 (REQUIRED)
#   6 sparse       mk-sparse.py: the Android sparse image the installer writes to userdata (read back)
#   7 parts        split-parts.py: < 2 GiB parts + image-manifest.json (+ SHA256SUMS)
#   8 privscan     privscan.py --golden (REQUIRED): structural checks always; the byte / file search for the owner's
#                  values only where the private reference files exist (the owner's PC, never CI)
# Tools from the project (ICELAND_TOOLS_DIR = a checkout's tools dir holding iceland_disk.py mk-sparse.py mk-small.py
# split-parts.py privscan.py; default: the WSL work tree paths).
set -euo pipefail
IN=$(realpath "${1:?INPUT_DIR}"); OUT=$(realpath -m "${2:?OUT_DIR}")
HERE=$(cd "$(dirname "$0")" && pwd)
B=${ICELAND_BUILD:-$HOME/mainline/build}
T=${ICELAND_TOOLS_DIR:-}
IMG=${T:-$B/wf/install/cand/image}; REC=${T:-$B/wf/generic/recipe}; PS=${T:-$B/wf/generic/privscan}
PRIV=${ICELAND_PRIV:-/nonexistent-no-private-references}
say() { echo "build: $*"; }
die() { say "FAIL $*"; exit 1; }
[ "$(id -u)" = 0 ] || die "needs root (privileged container)"
[ "$(uname -m)" = aarch64 ] || die "not aarch64: run inside the aarch64 container"
mkdir -p "$OUT"
if [ -n "$T" ]; then   # mk-small.py imports iceland_disk from the work tree path: give it that path in the container
	mkdir -p "$B/wf/install/cand/image"; cp "$T/iceland_disk.py" "$B/wf/install/cand/image/"
fi
# 1
bash "$HERE/tools/build-local-repo.sh" "$IN" /work/localrepo | tee "$OUT/local-repo.txt"
say "1 local repo: $(ls /work/localrepo/*.rpm | wc -l) packages"
# 2 (kiwi's own log in OUT/kiwi; the description is used as committed: desc/config.kiwi is generated by mk-kiwi.py on the PC)
rm -rf "$OUT/kiwi"
kiwi-ng --logfile "$OUT/kiwi.log" system build --description "$HERE/desc" --target-dir "$OUT/kiwi" > /dev/null 2>&1 \
	|| die "kiwi-ng system build (tail: $(tail -n 5 "$OUT/kiwi.log" | tr '\n' ' ' | cut -c1-400))"
RAW=$(ls "$OUT"/kiwi/*.raw | head -n 1); [ -s "$RAW" ] || die "no raw disk from kiwi"
grep -h -o 'iceland-\(config\|editboot\): .*' "$OUT/kiwi.log" | sed 's/^/build:   /' || :
say "2 kiwi: ${RAW##*/} $(du -h --apparent-size "$RAW" | cut -f1)"
# 3 4
python3 -I "$HERE/tools/kiwi2golden.py" "$RAW" "$OUT/run" --name kiwi-b150g | sed 's/^/build:   /'
python3 -I "$REC/mk-small.py" "$OUT/run/kiwi-b150g.json" --name kiwi-b150g-small | sed 's/^/build:   /'
rm -f "$OUT/run/kiwi-b150g.body"            # the small disk replaces it (same partitions; body copied)
say "3-4 golden + small: $OUT/run/kiwi-b150g-small.json"
# 5 (required)
ICELAND_BUILD=$B bash "$HERE/tools/image-check.sh" "$OUT/run/kiwi-b150g-small.json" "$OUT/check" "$HERE/desc/b149-packages.json" > /dev/null || :
tail -n 1 "$OUT/check/image-check.txt" | grep -q 'IMAGE-CHECK: PASS' || { grep '^FAIL' "$OUT/check/image-check.txt" | sed 's/^/build:   /'; die "5 image-check"; }
say "5 image check: $(tail -n 1 "$OUT/check/image-check.txt")"
# 6 7
python3 -I "$IMG/mk-sparse.py" "$OUT/run/kiwi-b150g-small.json" "$OUT/fedora-iceland-generic.sparse.img" | tail -n 2 | sed 's/^/build:   /'
python3 -I "$REC/split-parts.py" "$OUT/fedora-iceland-generic.sparse.img" "$OUT/parts" | tail -n 2 | sed 's/^/build:   /'
say "6-7 sparse + parts: $(ls "$OUT/parts" | wc -l) files"
# 8 (required)
python3 -I "$PS/privscan.py" --golden "$OUT/run/kiwi-b150g-small.json" --out "$OUT/privscan" --priv "$PRIV" > "$OUT/privscan.log" 2>&1 \
	|| die "8 privscan: $(tail -n 1 "$OUT/privscan.log")"
say "8 privscan: $(tail -n 1 "$OUT/privscan.log") (references: $(sed -n 's/.*references loaded (values never printed): //p' "$OUT/privscan.log" | head -n 1))"
say "DONE $(cat "$OUT/parts/SHA256SUMS" 2>/dev/null | wc -l) checksummed files in $OUT/parts"
