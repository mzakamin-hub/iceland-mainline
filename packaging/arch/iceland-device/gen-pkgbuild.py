"""Generate the Arch PKGBUILD of iceland-device from our Fedora spec (iceland-device 0.28-53).

    python3 -I gen-pkgbuild.py SPEC_DIR AUDIO_DIR OUT_DIR

SPEC_DIR = packaging/iceland-device of rel/iceland-device-0.28-53 (spec + files/), AUDIO_DIR = the repo's audio/.
Every `install` line of the spec's %install is carried over 1:1 (same paths: /usr/libexec/iceland etc.), with
%{SOURCEn} -> the file and %{buildroot} -> "$pkgdir". Fedora-only lines (dnf, SELinux, RPM keys, GNOME, KDE,
the dnf repo helpers) are left out and listed in DROPPED.txt; the Hyprland forms of the desktop pieces are the
split package iceland-device-hypr (files in hypr/). The result is reviewed by hand, not edited: re-run this script.
"""
import hashlib, os, re, shutil, sys

spec_dir, audio_dir, out = sys.argv[1:4]
spec = open(os.path.join(spec_dir, "iceland-device.spec")).read()
src = {m.group(1): m.group(2).strip() for m in re.finditer(r"^Source(\d+):\s*(\S+)", spec, re.M)}
version = re.search(r"^Version:\s*(\S+)", spec, re.M).group(1)
release = re.search(r"^Release:\s*(\d+)", spec, re.M).group(1)
inst = spec.split("\n%install\n", 1)[1].split("\n%pre\n", 1)[0]

# lines that only make sense on Fedora (or in a KDE / GNOME session) -> DROPPED.txt
DROP = [
    ("dnf5", "dnf configuration (pacman: IgnorePkg in the install plan instead)"),
    ("yum.repos.d", "dnf repository"), ("rpm-gpg", "RPM signing key"),
    ("libdnf5-plugins", "dnf snapshot action (pacman hook 05-iceland-snapshot.hook in -hypr? no: TODO, see INVENTORY)"),
    ("dnf/protected.d", "dnf protected list"), ("/var/lib/iceland/repo", "local dnf repo"),
    ("iceland-repo-sync", "dnf local repo sync"), ("iceland-firmware-fetch", "dnf firmware fetch"),
    ("firmware-pins.tsv", "dnf firmware fetch pins"), ("iceland-update-check", "dnf update check"),
    ("iceland-hold-migrate", "dnf hold migration"), ("selinux", "SELinux module (Arch: no SELinux)"),
    ("no-system-upgrade", "Fedora offline-upgrade polkit rule"),
    ("50-iceland-abrt.preset", "Fedora ABRT preset"),
    ("gnome-shell/extensions", "GNOME Shell extension (bar toggle in -hypr)"),
    ("glib-2.0/schemas", "GNOME GSettings override"), ("dconf/db/gdm.d", "GDM greeter default"),
    ("iceland-ambient-default", "GNOME ambient reset (-hypr has iceland-ambient)"),
    ("powerdevilrc", "KDE PowerDevil (Omarchy shell idle settings in -hypr)"),
    ("kde-charge-limit", "KDE polkit rule"), ("plasmoids", "KDE plasmoid (bar toggle in -hypr)"),
    ("iceland-kde-", "KDE helper"), ("kde-curve", "KDE helper state"),
    ("50-iceland-kde-secrets", "KWallet env"), ("51-iceland-kde-powerdevil", "PowerDevil env"),
    ("session-first", "KDE session-first dir"), ("kwalletrc", "KWallet"),
    ("iceland-secrets-migrate", "KWallet migration"), ("iceland-shot", "Spectacle screenshot (-hypr: grim form)"),
    ("/usr/bin/iceland-dmmap", "symlink kept below by hand"),
]
keep, dropped, files_used = [], [], set()
for line in inst.splitlines():
    s = line.strip()
    if not s or s.startswith("#"):
        keep.append(line)
        continue
    why = next((w for k, w in DROP if k in s), None)
    if why:
        dropped.append("%s\t%s" % (why, s))
        continue
    def sub(m):
        f = src[m.group(1)]
        files_used.add(f)
        return '"$srcdir/%s"' % f
    s = re.sub(r"%\{SOURCE(\d+)\}", sub, s)
    s = s.replace("%{buildroot}", '"$pkgdir"').replace("%{name}", "iceland-device")
    s = s.replace("audioreach-topology/", '"$srcdir"/audioreach-topology/') \
         .replace(" audio/", ' "$srcdir"/audio/').replace(" tuned/", ' "$srcdir"/tuned/')
    keep.append("  " + s)
# the dmmap link on PATH (the spec's line carries an install -d in front)
keep.append('  install -d "$pkgdir"/usr/bin && ln -s ../libexec/iceland/iceland-dmmap "$pkgdir"/usr/bin/iceland-dmmap')

os.makedirs(out, exist_ok=True)
for f in sorted(files_used):
    shutil.copy2(os.path.join(spec_dir, "files", f), os.path.join(out, f))
if os.path.isdir(os.path.join(out, "tuned")):
    shutil.rmtree(os.path.join(out, "tuned"))
shutil.copytree(os.path.join(spec_dir, "files", "tuned"), os.path.join(out, "tuned"))
if os.path.isdir(os.path.join(out, "audio")):
    shutil.rmtree(os.path.join(out, "audio"))
shutil.copytree(audio_dir, os.path.join(out, "audio"))

def sha(p):
    return hashlib.sha256(open(os.path.join(out, p), "rb").read()).hexdigest()

srcs = sorted(files_used)
backup = ["etc/iceland/" + x for x in ("boot.conf", "battery-guard.conf", "thermal.conf", "refresh.conf",
          "launchboost.conf", "cover-detect.conf", "snapshot.conf")]
pk = []
pk.append("# Maintainer: iceland project (generated by gen-pkgbuild.py from iceland-device.spec %s-%s; do not edit)" % (version, release))
pk.append("# SPDX-License-Identifier: GPL-2.0-or-later")
pk.append("pkgbase=iceland-device")
pk.append("pkgname=(iceland-device iceland-device-hypr)")
pk.append("pkgver=%s.%s" % (version, release))
pk.append("pkgrel=1")
pk.append("pkgdesc='OnePlus Pad 4 (iceland) device settings for Arch Linux ARM / Omarchy (port of iceland-device %s-%s)'" % (version, release))
pk.append("arch=(any)")
pk.append("url='https://github.com/mzakamin-hub/iceland-mainline'")
pk.append("license=('GPL-2.0-or-later' 'BSD-3-Clause')")
pk.append("makedepends=(m4 alsa-utils)")
pk.append("_audioreach=993a17d")
pk.append("source=(\"audioreach-topology::git+https://github.com/linux-msm/audioreach-topology.git#commit=993a17d\"")
for f in srcs:
    pk.append("        '%s'" % f)
pk.append("        hypr.tar)")
pk.append("sha256sums=('SKIP'")
for f in srcs:
    pk.append("            '%s'" % sha(f))
pk.append("            'SKIP')")
pk.append("")
pk.append("prepare() {")
pk.append("  # audio overlay and tuned profiles travel as directories next to the PKGBUILD")
pk.append('  cp -a "$startdir/audio" "$startdir/tuned" "$srcdir/"')
pk.append('  # Arch: iceland-cmdline only manages the Arch entries (arch1-*-a1.conf); Fedora\'s copy manages its own.')
pk.append('  # The two /etc/iceland/boot.conf must stay identical (ROOTFS-PLAN: copied from Fedora at rehearsal build).')
pk.append('  sed -i \'s#"$R"/boot/loader/entries/\\*.conf#"$R"/boot/loader/entries/arch1-*-a1.conf#\' "$srcdir/iceland-cmdline"')
pk.append("}")
pk.append("")
pk.append("build() {")
pk.append('  cp -a "$srcdir"/audio/topology/. "$srcdir"/audioreach-topology/')
pk.append('  cd "$srcdir"/audioreach-topology')
pk.append("  m4 -I . OnePlus-Pad4.m4 > OnePlus-Pad4.conf")
pk.append("  alsatplg -c OnePlus-Pad4.conf -o OnePlus-Pad4-tplg.bin")
pk.append("  grep -q 'max \"8192\"' OnePlus-Pad4.conf")
pk.append("}")
pk.append("")
pk.append("package_iceland-device() {")
pk.append("  depends=(linux-iceland 'iceland-firmware>=11.A.38.6' iceland-coexist bluez python python-gobject polkit iw ethtool")
pk.append("           qbootctl iproute2 alsa-utils alsa-ucm-conf tuned tuned-ppd hexagonrpc libssc iio-sensor-proxy-iceland")
pk.append("           upower-iceland libcamera-ipa pipewire-libcamera 'wireplumber>=0.5.18' swh-plugins pipewire fuse3")
pk.append("           btrfs-progs util-linux device-mapper dracut nbd busybox irqbalance zram-generator chrony")
pk.append("           networkmanager diffutils)")
pk.append("  optdepends=('iceland-device-hypr: the Hyprland / Omarchy session parts')")
pk.append("  backup=(%s)" % " ".join(backup))
pk.append("  install=iceland-device.install")
pk.append("  cd \"$srcdir\"")
pk.extend(keep)
pk.append("  # Fedora-only directories the spec creates that make no sense here are not created")
pk.append("}")
pk.append("")
pk.append("package_iceland-device-hypr() {")
pk.append("  pkgdesc='OnePlus Pad 4 (iceland): the Hyprland / Omarchy session parts (refresh switch, bypass toggle, ambient")
pk.append("brightness, idle policy, rotation, cover mode)'")
pk.append("  depends=(iceland-device hyprland wlr-randr brightnessctl python python-gobject iio-sensor-proxy-iceland")
pk.append("           libnotify grim)")
pk.append("  install=iceland-device-hypr.install")
pk.append('  bsdtar -xf "$srcdir/hypr.tar" -C "$pkgdir"')
pk.append("}")
open(os.path.join(out, "PKGBUILD"), "w").write("\n".join(pk) + "\n")
open(os.path.join(out, "DROPPED.txt"), "w").write(
    "# spec %%install lines not carried over to Arch (reason<TAB>line)\n" + "\n".join(dropped) + "\n")
print("PKGBUILD: %d install lines kept, %d dropped, %d source files" %
      (sum(1 for l in keep if l.startswith("  ")), len(dropped), len(srcs)))
